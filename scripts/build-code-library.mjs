// Bundles the files in code/ into code-library.js, which the website loads.
// The .v / .sv files are the source of truth: edit them, test them, then rebuild.
//   node scripts/check-code.mjs            test every design
//   node scripts/build-code-library.mjs    rebuild the bundle
//   node scripts/build-code-library.mjs --check   fail if the bundle is out of date

import fs from 'node:fs';

const root = new URL('../', import.meta.url);
const read = p => fs.readFileSync(new URL(p, root), 'utf8');
const meta = JSON.parse(read('code/library.json'));

const onDisk = fs.readdirSync(new URL('code/', root), { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort();
const listed = meta.map(m => m.id).sort();
if (onDisk.join() !== listed.join()) {
  console.error('code/library.json and the folders in code/ do not match.');
  process.exit(1);
}

const library = meta.map(m => ({
  ...m,
  v: read(`code/${m.id}/${m.id}.v`),
  sv: read(`code/${m.id}/${m.id}.sv`),
  tb: read(`code/${m.id}/tb_${m.id}.v`),
}));
const out = '// GENERATED by scripts/build-code-library.mjs from the files in code/. Do not edit by hand.\n' +
  'window.CODE_LIBRARY = ' + JSON.stringify(library) + ';\n';

if (process.argv.includes('--check')) {
  const current = fs.existsSync(new URL('code-library.js', root)) ? read('code-library.js') : '';
  if (current !== out) { console.error('code-library.js is out of date: run node scripts/build-code-library.mjs'); process.exit(1); }
  console.log('code-library.js is up to date.');
} else {
  fs.writeFileSync(new URL('code-library.js', root), out);
  console.log(`code-library.js written: ${library.length} designs, ${(out.length / 1024).toFixed(0)} KB`);
}
